import { z } from 'zod';
import { paginatedResponseSchema } from './pagination.js';
import { sourceTypeSchema } from './sources.js';
import { cleanString } from './text.js';

export const messageRoleSchema = z.enum(['USER', 'ASSISTANT']);
export type MessageRole = z.infer<typeof messageRoleSchema>;

/** Shared by messages and lessons. */
export const generationStatusSchema = z.enum(['COMPLETE', 'ERROR']);
export type GenerationStatus = z.infer<typeof generationStatusSchema>;

export const feedbackSchema = z.enum(['UP', 'DOWN']);
export type Feedback = z.infer<typeof feedbackSchema>;

/**
 * One `[n]` marker's source, copied at answer time (docs/03-database-design.md §5). A snapshot, so
 * it survives the source being reprocessed or deleted. Reused by lessons.
 */
export const citationSnapshotSchema = z.strictObject({
  marker: z.number().int().min(1),
  sourceId: z.uuid(),
  sourceTitle: z.string(),
  sourceType: sourceTypeSchema,
  snippet: z.string(),
  /** PDF. */
  pageNumber: z.number().int().min(1).nullable(),
  /** YouTube. */
  startSeconds: z.number().min(0).nullable(),
  /** Website / text. */
  headingPath: z.string().nullable(),
  charStart: z.number().int().min(0).nullable(),
  charEnd: z.number().int().min(0).nullable(),
});
export type CitationSnapshot = z.infer<typeof citationSnapshotSchema>;

export const citationSnapshotsSchema = z.array(citationSnapshotSchema);

export const CONVERSATION_TITLE_MAX = 200;
/** One chat message from the user, in characters. */
export const MESSAGE_CONTENT_MAX = 4_000;

const conversationTitleSchema = cleanString.pipe(
  z
    .string()
    .trim()
    .min(1, 'Title is required')
    .max(CONVERSATION_TITLE_MAX, `Title must be at most ${CONVERSATION_TITLE_MAX} characters`),
);

/** `POST /notebooks/:notebookId/conversations`. `lessonId` scopes the chat to a lesson (Phase 9). */
export const createConversationSchema = z.strictObject({ lessonId: z.uuid().optional() });
export type CreateConversationInput = z.infer<typeof createConversationSchema>;

/** `PATCH /conversations/:conversationId`. */
export const updateConversationSchema = z.strictObject({ title: conversationTitleSchema });
export type UpdateConversationInput = z.infer<typeof updateConversationSchema>;

export const conversationSchema = z.object({
  id: z.uuid(),
  notebookId: z.uuid(),
  lessonId: z.uuid().nullable(),
  title: z.string(),
  lastMessageAt: z.iso.datetime(),
  createdAt: z.iso.datetime(),
  updatedAt: z.iso.datetime(),
});
export type Conversation = z.infer<typeof conversationSchema>;

export const conversationListSchema = paginatedResponseSchema(conversationSchema);

/**
 * `POST /conversations/:conversationId/messages`. Only the new message is used; the server builds
 * the history from the database, and anything else in the body (e.g. a client-side history) is
 * dropped. `id` is generated by the client, so a resend is recognized and not duplicated.
 */
export const sendMessageSchema = z.object({
  id: z.uuid(),
  content: cleanString.pipe(
    z
      .string()
      .trim()
      .min(1, 'Message is required')
      .max(MESSAGE_CONTENT_MAX, `Message must be at most ${MESSAGE_CONTENT_MAX} characters`),
  ),
});
export type SendMessageInput = z.infer<typeof sendMessageSchema>;

/** `PUT /messages/:messageId/feedback`. `null` removes the feedback. */
export const messageFeedbackSchema = z.strictObject({ value: feedbackSchema.nullable() });
export type MessageFeedbackInput = z.infer<typeof messageFeedbackSchema>;

export const messageSchema = z.object({
  id: z.uuid(),
  conversationId: z.uuid(),
  seq: z.number().int().min(1),
  role: messageRoleSchema,
  /** With `[n]` markers that match `citations[].marker`. */
  content: z.string(),
  citations: citationSnapshotsSchema,
  status: generationStatusSchema,
  feedback: feedbackSchema.nullable(),
  createdAt: z.iso.datetime(),
});
export type Message = z.infer<typeof messageSchema>;

/** Newest first; `nextCursor` loads older messages. */
export const messageListSchema = paginatedResponseSchema(messageSchema);

/**
 * Custom parts of the chat stream (AI SDK UI message stream, docs/04-api-design.md §8), sent as
 * `data-<name>` chunks. `start` carries the answer's message ID and `finish` its trace ID in the
 * message metadata.
 */
export const chatStreamDataSchemas = {
  /** Progress line, e.g. "Searching your sources…". Not kept in the message. */
  status: z.object({ message: z.string() }),
  /** Final citation snapshots, once the answer is complete. */
  citations: citationSnapshotsSchema,
  /** Tutor only: the learner seems ready → offer "Mark module done" (never done by the server). */
  action: z.object({ type: z.literal('SUGGEST_COMPLETE'), moduleId: z.uuid() }),
  /** Why the answer failed; the message is saved as `ERROR`. */
  error: z.object({ code: z.string(), message: z.string() }),
};

export const chatMessageMetadataSchema = z.object({ traceId: z.string().optional() });
export type ChatMessageMetadata = z.infer<typeof chatMessageMetadataSchema>;
